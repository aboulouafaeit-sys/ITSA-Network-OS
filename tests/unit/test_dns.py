"""Unit tests for DNS diagnostics module."""

import unittest
from itsa_network_os.network.dns import DNSDiagnosticResult, DNSDiagnostics
from itsa_network_os.network.models import DNSServerInfo


class TestDNSDiagnostics(unittest.TestCase):
    """Test safe DNS query resolution and mock handling."""

    def test_mock_dns_query(self) -> None:
        result = DNSDiagnostics.query("example.com", use_mock=True)
        self.assertIsInstance(result, DNSDiagnosticResult)
        self.assertEqual(result.target_host, "example.com")
        self.assertEqual(result.status, "SUCCESS")
        self.assertGreater(len(result.records), 0)
        self.assertGreater(result.response_time_ms, 0.0)

    def test_mock_dns_to_dict_serializable(self) -> None:
        result = DNSDiagnostics.query("cloudflare.com", use_mock=True)
        data = result.to_dict()
        self.assertIn("target_host", data)
        self.assertIn("records", data)
        self.assertIn("response_time_ms", data)
        self.assertEqual(data["status"], "SUCCESS")

    def test_get_system_resolvers_returns_list(self) -> None:
        resolvers = DNSDiagnostics.get_system_resolvers()
        self.assertIsInstance(resolvers, list)
        self.assertGreater(len(resolvers), 0)

    def test_get_system_dns_servers_mock(self) -> None:
        servers = DNSDiagnostics.get_system_dns_servers(use_mock=True)
        self.assertEqual(len(servers), 2)
        for s in servers:
            self.assertIsInstance(s, DNSServerInfo)
            self.assertEqual(s.scope, "system")
            self.assertIsNone(s.interface)
            self.assertEqual(s.provenance, "mock")
        self.assertEqual(servers[0].address, "1.1.1.1")
        self.assertEqual(servers[1].address, "1.0.0.1")

    def test_get_system_dns_servers_parsing_and_deduplication(self) -> None:
        sample_resolv = (
            "# Generated by NetworkManager\n"
            "; another comment\n"
            "nameserver 10.125.191.5\n"
            "nameserver 8.8.8.8\n"
            "nameserver 10.125.191.5\n"  # Duplicate: must be ignored
            "nameserver 2001:4860:4860::8888\n"
            "nameserver not-an-ip\n"  # Malformed: must be ignored
            "search localdomain\n"
        )
        servers = DNSDiagnostics.get_system_dns_servers(use_mock=False, resolv_content=sample_resolv)
        self.assertEqual(len(servers), 3)

        self.assertEqual(servers[0].address, "10.125.191.5")
        self.assertEqual(servers[0].scope, "system")
        self.assertIsNone(servers[0].interface)
        self.assertEqual(servers[0].provenance, "resolv.conf")

        self.assertEqual(servers[1].address, "8.8.8.8")
        self.assertEqual(servers[2].address, "2001:4860:4860::8888")

    def test_get_system_dns_servers_empty_or_missing(self) -> None:
        self.assertEqual(DNSDiagnostics.get_system_dns_servers(use_mock=False, resolv_content=""), [])
        self.assertEqual(
            DNSDiagnostics.get_system_dns_servers(
                use_mock=False, resolv_content="# No nameservers here\nsearch home\n"
            ),
            [],
        )

    def test_parse_nmcli_dev_show_dns(self) -> None:
        sample_nmcli = (
            "GENERAL.DEVICE:wlo1\n"
            "IP4.DNS[1]:10.125.191.5\n"
            "IP6.DNS[1]:fe80::1\n"
            "GENERAL.DEVICE:eth0\n"
            "IP4.DNS[1]:192.168.1.1\n"
            "GENERAL.DEVICE:lo\n"
        )
        parsed = DNSDiagnostics.parse_nmcli_dev_show_dns(sample_nmcli)
        self.assertIn("wlo1", parsed)
        self.assertIn("eth0", parsed)
        self.assertNotIn("lo", parsed)

        wlo1_dns = parsed["wlo1"]
        self.assertEqual(len(wlo1_dns), 2)
        self.assertEqual(wlo1_dns[0].address, "10.125.191.5")
        self.assertEqual(wlo1_dns[0].scope, "interface")
        self.assertEqual(wlo1_dns[0].interface, "wlo1")
        self.assertEqual(wlo1_dns[0].provenance, "networkmanager")

        self.assertEqual(wlo1_dns[1].address, "fe80::1")
        self.assertEqual(wlo1_dns[1].scope, "interface")
        self.assertEqual(wlo1_dns[1].interface, "wlo1")

        eth0_dns = parsed["eth0"]
        self.assertEqual(len(eth0_dns), 1)
        self.assertEqual(eth0_dns[0].address, "192.168.1.1")
        self.assertEqual(eth0_dns[0].scope, "interface")
        self.assertEqual(eth0_dns[0].interface, "eth0")

    def test_get_interface_dns_servers_mock(self) -> None:
        mapping = DNSDiagnostics.get_interface_dns_servers(use_mock=True)
        self.assertIn("eth0", mapping)
        eth0_entry = mapping["eth0"][0]
        self.assertEqual(eth0_entry.address, "192.168.1.1")
        self.assertEqual(eth0_entry.scope, "interface")
        self.assertEqual(eth0_entry.interface, "eth0")
        self.assertEqual(eth0_entry.provenance, "mock")


if __name__ == "__main__":
    unittest.main()
